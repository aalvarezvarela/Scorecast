"""Write ``nba_ou.prediction.input_support_table`` from an intermediate dataset.

The table lists, per injury-news column, the horizons where too few training
rows carry a value for a model trained there to have learnt it (see
``nba_ou.prediction.input_limits``). Regenerate it when the served models'
training dataset changes:

    poetry run python scripts/build_input_support_table.py \
        data/train_data/intermediate_line_data_2_5_20261016.parquet
"""

from __future__ import annotations

import argparse
import pprint
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq
from nba_ou.prediction.input_limits import (
    NEWS_PREFIXES,
    SUPPORT_THRESHOLD,
    unsupported_news_columns,
)

OUTPUT = (
    Path(__file__).resolve().parents[1] / "src/nba_ou/prediction/input_support_table.py"
)

TEMPLATE = '''"""Generated by scripts/build_input_support_table.py; do not edit.

Per injury-news column, the horizons where fewer than {threshold:.0%} of the
training rows carry a value (not NaN, not 0), measured on SOURCE. Read by
``nba_ou.prediction.input_limits``.
"""

SOURCE = {source!r}
THRESHOLD = {threshold!r}

UNSUPPORTED_NEWS_COLUMNS: dict[str, tuple[int, ...]] = {table}
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("dataset", type=Path, help="intermediate dataset (.parquet)")
    parser.add_argument("--threshold", type=float, default=SUPPORT_THRESHOLD)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    names = pq.read_schema(args.dataset).names
    columns = ["TIME_TO_MATCH_MIN", *(c for c in names if c.startswith(NEWS_PREFIXES))]
    frame = pd.read_parquet(args.dataset, columns=columns)
    table = unsupported_news_columns(frame, threshold=args.threshold)
    args.output.write_text(
        TEMPLATE.format(
            source=args.dataset.name,
            threshold=args.threshold,
            table=pprint.pformat(table, width=80, sort_dicts=True),
        )
    )
    print(f"{len(table)} column(s) limited at some horizon -> {args.output}")


if __name__ == "__main__":
    main()
