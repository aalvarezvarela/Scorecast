"""Export each job's requirements file from poetry.lock.

    python scripts/export_requirements.py           # rewrite requirements/
    python scripts/export_requirements.py --check   # fail if any file is stale

pyproject.toml is the single source of dependencies; the files in requirements/
are generated from the lock and committed, so GitHub Actions jobs install
with pip and never need Poetry. Each job gets the Poetry groups it uses; jobs
that fit or load XGBoost get a CUDA and a CPU variant (requirements/README.md).

Needs the export plugin: ``poetry self add poetry-plugin-export``.
"""

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = REPO_ROOT / "requirements"

# file stem -> Poetry groups, in the order they are passed to the export.
JOBS: dict[str, tuple[str, ...]] = {
    "predict-cuda": ("main", "cuda", "scrape"),
    "predict-cpu": ("main", "cpu", "scrape"),
    "predict-tabpfn-cuda": ("main", "cuda", "scrape", "tabpfn"),
    "predict-tabpfn-cpu": ("main", "cpu", "scrape", "tabpfn"),
    "retrain-cuda": ("main", "cuda"),
    "retrain-cpu": ("main", "cpu"),
    "db-update": ("main", "scrape"),
    "core": ("main",),
    "tests-cpu": ("main", "cpu", "scrape", "train", "dev"),
}


def _header(groups: tuple[str, ...]) -> str:
    return (
        "# Generated by scripts/export_requirements.py from poetry.lock; do not edit.\n"
        f"# Poetry groups: {', '.join(groups)}\n"
        "#\n"
        "#     pip install -r <this file>\n"
        "#     pip install --no-deps -e .\n"
    )


def export(groups: tuple[str, ...]) -> str:
    result = subprocess.run(
        [
            "poetry",
            "export",
            "--format",
            "requirements.txt",
            "--only",
            ",".join(groups),
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"poetry export failed for {groups}:\n{result.stderr}")
    return _header(groups) + result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Write nothing; exit 1 if any file differs from a fresh export.",
    )
    args = parser.parse_args()

    expected = {
        OUTPUT_DIR / f"{stem}.txt": export(groups) for stem, groups in JOBS.items()
    }
    unexpected = sorted(set(OUTPUT_DIR.glob("*.txt")) - set(expected))

    if args.check:
        stale = [
            path
            for path, text in expected.items()
            if not path.exists() or path.read_text() != text
        ]
        for path in stale + unexpected:
            print(f"stale: {path.relative_to(REPO_ROOT)}")
        if stale or unexpected:
            print("Run: python scripts/export_requirements.py")
            return 1
        print(f"{len(expected)} requirements files match poetry.lock")
        return 0

    OUTPUT_DIR.mkdir(exist_ok=True)
    for path, text in expected.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    for path in unexpected:
        path.unlink()
        print(f"removed {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
